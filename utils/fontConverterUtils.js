/* ============================================================
   8. UNICODE → SHIVAJI
   ============================================================ */

export function unicodeToShivaji(sourceText) {
  if (!sourceText) return "";

  let text = preProcess(sourceText);

  text = normalizeDevanagari(text);


  // Shivaji reph positioning
  text = moveRephToEnd(text, "-");

  // Shivaji uses "i" for short-i matra positioning
  text = moveChhotiI(text, "i");

  return convertShivaji(text);
}



/* ============================================================
   9. KRUTIDEV → UNICODE
   ============================================================ */

export function krutidevToUnicode(text) {
  if (!text) return "";

  try {
    return kru2uni(text);
  } catch (error) {
    console.error("[FontConverter] KrutiDev → Unicode failed:", error);
    throw new Error("KrutiDev → Unicode conversion failed.");
  }
}


/* ============================================================
   10. SHIVAJI → UNICODE
   ============================================================ */

/*
 * Shivaji and KrutiDev share a large part of their legacy
 * character space, but some Shivaji codes are different.
 *
 * Convert only the known Shivaji-specific codes first.
 */
export function shivajiToUnicode(text) {
  if (!text) return "";

  let t = String(text);

  /*
   * IMPORTANT:
   * Long sequences must be handled before single characters.
   */
  t = t.replace(/n~o/g, "}");

  /*
   * Shivaji-specific conjuncts.
   */
  t = t.replace(/ð/g, ")");
  t = t.replace(/†/g, "ॐ");
  t = t.replace(/J/g, "ऱ");

  /*
   * Shivaji half-letter differences.
   *
   * These are intentionally kept compatible with the existing
   * TNT behaviour.
   */
  t = t.replace(/I/g, "i");
  t = t.replace(/C/g, "c");
  t = t.replace(/E/g, "e");
  t = t.replace(/Y/g, "y");
  t = t.replace(/O/g, "o");

  try {
    return kru2uni(t);
  } catch (error) {
    console.error("[FontConverter] Shivaji → Unicode failed:", error);
    throw new Error("Shivaji → Unicode conversion failed.");
  }
}


