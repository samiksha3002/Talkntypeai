/* ============================================================
   1. COMMON HELPERS
   ============================================================ */

function preProcess(text) {
  if (typeof text !== "string") return "";

  return text
    .replace(/<\/?p[^>]*>/gi, "\n")
    .replace(/<br\s*\/?>/gi, "\n")
    .replace(/<[^>]+>/g, "")
    .replace(/&nbsp;/gi, " ")
    .replace(/\u00A0/g, " ")
    .replace(/\r\n/g, "\n")
    .replace(/\r/g, "\n")
    .normalize("NFC");
}


/*
 * Normalize common Devanagari sequences.
 *
 * This is intentionally conservative.
 * We do NOT randomly rewrite characters because Marathi/Hindi
 * Unicode can contain valid combinations that must remain intact.
 */
function normalizeDevanagari(text) {
  return text
    .normalize("NFC")
    .replace(/क़/g, "क़")
    .replace(/ख़/g, "ख़")
    .replace(/ग़/g, "ग़")
    .replace(/ज़/g, "ज़")
    .replace(/ड़/g, "ड़")
    .replace(/ढ़/g, "ढ़")
    .replace(/फ़/g, "फ़")
    .replace(/य़/g, "य़")
    .replace(/ऱ/g, "ऱ")
    .replace(/ऴ/g, "ऴ");
}


/* ============================================================
   2. UNICODE REPH HANDLING
   ============================================================ */

/*
 * Unicode:
 *
 *     र् + consonant cluster + matra
 *
 * Legacy:
 *
 *     consonant cluster + matra + Z
 *
 * Example:
 *
 *     र्त   → तZ
 *     र्कि  → fकZ
 *     र्क्षि → fक्षZ
 *
 * This handles a complete consonant cluster instead of only
 * looking at the first consonant.
 */
function moveRephToEnd(text, rephChar = "Z") {
  const consonant = "[क-हऴ]";
  const nukta = "़?";

  const cluster =
    `${consonant}${nukta}(?:्${consonant}${nukta})*`;

  const matras = "[ािीुूृॄेैोौंःँॅॉॊ]*";

  const regex = new RegExp(
    `र्(${cluster})(${matras})`,
    "g"
  );

  return text.replace(regex, `$1$2${rephChar}`);
}


/* ============================================================
   3. CHHOTI-I HANDLING
   ============================================================ */

/*
 * Unicode stores:
 *
 *     कि
 *     क्रि
 *     क्षि
 *
 * Legacy fonts normally require:
 *
 *     f + consonant cluster
 *
 * We move ि to the beginning of the complete consonant cluster.
 */
function moveChhotiI(text, marker = "f") {
  const consonant = "[क-हऴ]";
  const cluster =
    `${consonant}़?(?:्${consonant}़?)*`;

  const regex = new RegExp(
    `(${cluster})ि`,
    "g"
  );

  return text.replace(regex, `${marker}$1`);
}


/* ============================================================
   4. GENERIC LONGEST-MATCH CONVERTER
   ============================================================ */

/*
 * IMPORTANT:
 *
 * We do NOT do:
 *
 *   text.replace(A)
 *   text.replace(B)
 *   text.replace(C)
 *
 * because output generated by A can accidentally become input
 * for B or C.
 *
 * Instead we scan the Unicode text once and always choose the
 * longest matching Unicode token.
 */
function createLongestMatchConverter(mapping) {
  const entries = Object.entries(mapping)
    .filter(([from]) => from.length > 0)
    .sort((a, b) => b[0].length - a[0].length);

  return function convertText(input) {
    if (!input) return "";

    let output = "";
    let index = 0;

    while (index < input.length) {
      let matched = false;

      for (const [from, to] of entries) {
        if (input.startsWith(from, index)) {
          output += to;
          index += from.length;
          matched = true;
          break;
        }
      }

      /*
       * If a character is not part of the legacy mapping,
       * preserve it instead of silently deleting it.
       *
       * This is especially useful for:
       * - English
       * - new Unicode characters
       * - legal punctuation
       * - unknown Marathi symbols
       */
      if (!matched) {
        output += input[index];
        index++;
      }
    }

    return output;
  };
}


